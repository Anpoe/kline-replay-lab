import type { DecisionPlanValue } from './decisionPlan.ts';

export type DecisionRecord = {
  id: string; barTimestamp: number; referencePrice: number; decision: DecisionPlanValue;
  submittedAt: string; backfilled?: boolean; autoGenerated?: boolean;
};
export function hasDecisionPlanContent(value: DecisionPlanValue) {
  return Boolean([value.marketState, value.location, value.stop, value.target, value.note].some(v => v.trim()) || value.reasons.some(v => v.trim()));
}
export function validateDecisionPlan(value: DecisionPlanValue): DecisionPlanValue {
  if (!hasDecisionPlanContent(value)) throw new Error('决策内容为空，请先填写计划。');
  for (const [label, price] of [['止损', value.stop], ['目标', value.target]]) {
    if (price.trim() && (!Number.isFinite(Number(price)) || Number(price) <= 0)) throw new Error(label + '价格需大于 0，或留空。');
  }
  return { ...value, reasons: [...value.reasons] };
}
export function decisionPlanStatus(value: DecisionPlanValue) {
  if (new Set(value.reasons.filter(v => v.trim())).size < 2) return '再找一个独立理由';
  if (!value.marketState.trim() || !value.location.trim()) return '待补市场 / 位置';
  if (!value.stop.trim() || !value.target.trim()) return '待补止损 / 目标';
  return '计划已填写';
}
export function commitDecisionRecord<T extends DecisionRecord>(records: T[], record: T) {
  if (!(record.barTimestamp > 0) || !Number.isFinite(record.barTimestamp) || !(record.referencePrice > 0) || !Number.isFinite(record.referencePrice)) throw new Error('请等待当前图表行情返回后保存决策。');
  const automatic = !record.backfilled ? records.find(item => item.autoGenerated && item.barTimestamp === record.barTimestamp) : undefined;
  const saved = { ...record, id: automatic?.id ?? record.id, decision: validateDecisionPlan(record.decision) };
  return { saved, records: automatic ? records.map(item => item.id === automatic.id ? saved : item) : [...records, saved] };
}
export function updateDecisionRecord<T extends DecisionRecord>(records: T[], id: string, value: DecisionPlanValue): T[] {
  if (!records.some(item => item.id === id)) throw new Error('这份决策已不存在，请重新读取记录。');
  const decision = validateDecisionPlan(value);
  return records.map(item => item.id === id ? { ...item, decision } : item);
}
export function removeDecisionRecord<T extends { id: string }>(records: T[], id: string): T[] { return records.filter(item => item.id !== id); }
export function normalizeDecisionTag(value: string) {
  const tag = value.trim().replace(/\s+/g, ' ').slice(0, 20);
  if (!tag) throw new Error('标签不能为空。');
  return tag;
}

export function latestEntryDecisionRecord<T extends DecisionRecord>(records: T[], timestamp: number) {
  return records.filter(record => !record.autoGenerated && !record.backfilled && record.barTimestamp <= timestamp)
    .sort((a,b) => a.barTimestamp - b.barTimestamp || a.submittedAt.localeCompare(b.submittedAt)).at(-1);
}
export function renameDecisionReason(value: DecisionPlanValue, previous: string, next: string): DecisionPlanValue {
  return { ...value, reasons: value.reasons.map(reason => reason === previous ? next : reason) };
}

export function decisionProtectionMatches(value: Pick<DecisionPlanValue, 'stop' | 'target'>, stop: string, target: string) {
  const equal = (left: string, right: string) => left.trim() === '' || right.trim() === '' ? left.trim() === right.trim() : Number.isFinite(Number(left)) && Number(left) === Number(right);
  return equal(value.stop, stop) && equal(value.target, target);
}

export function ensureProtectiveDecisionRecord<T extends DecisionRecord>(records: T[], incoming: T) {
  const manual = records.find(record => !record.autoGenerated && record.barTimestamp === incoming.barTimestamp && decisionProtectionMatches(record.decision, incoming.decision.stop, incoming.decision.target));
  if (manual) return { records, saved: manual, changed: false };
  const automatic = records.find(record => record.autoGenerated && record.barTimestamp === incoming.barTimestamp);
  if (automatic && JSON.stringify(automatic.decision) === JSON.stringify(incoming.decision)) return { records, saved: automatic, changed: false };
  const saved = { ...incoming, id: automatic?.id ?? incoming.id, autoGenerated: true, decision: validateDecisionPlan(incoming.decision) };
  return { saved, records: automatic ? records.map(record => record.id === automatic.id ? saved : record) : [...records, saved], changed: true };
}

export function createEmptyDecisionPlan(): DecisionPlanValue {
  return { marketState: '', location: '', reasons: [], stop: '', target: '', note: '' };
}
export function draftAfterDecisionSaved(current: DecisionPlanValue, submitted: DecisionPlanValue, returnDraft = createEmptyDecisionPlan()): DecisionPlanValue {
  const same = current.marketState === submitted.marketState && current.location === submitted.location
    && current.stop === submitted.stop && current.target === submitted.target && current.note === submitted.note
    && JSON.stringify(current.reasons) === JSON.stringify(submitted.reasons);
  return same ? { ...returnDraft, reasons: [...returnDraft.reasons] } : current;
}
export function decisionForEntry(draft: DecisionPlanValue, records: DecisionRecord[], timestamp: number): DecisionPlanValue {
  return hasDecisionPlanContent(draft) ? draft : latestEntryDecisionRecord(records, timestamp)?.decision ?? draft;
}

type DecisionDrawing = { name: string; points: { value?: number }[] };
export function decisionProtectionFromDrawings(previous: DecisionDrawing[], next: DecisionDrawing[]) {
  const position = (drawings: DecisionDrawing[]) => drawings.findLast(item => item.name === 'trainingPosition' && item.points.length >= 3);
  const before = position(previous), after = position(next);
  if (!before && !after) return null;
  const values = (drawing?: DecisionDrawing) => {
    const price = (value?: number) => value != null && Number.isFinite(value) && value > 0 ? value : undefined;
    return { stop: price(drawing?.points[2]?.value), target: price(drawing?.points[1]?.value) };
  };
  const left = values(before), right = values(after);
  return Boolean(before) === Boolean(after) && left.stop === right.stop && left.target === right.target ? null : right;
}
